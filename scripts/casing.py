#!/usr/bin/env python3
# Generates tal/src/casing.inc, the case tables of tal::text: the simple case folding (statuses C
# and S of CaseFolding.txt) and the simple lowercase mapping (UnicodeData.txt). It takes them from
# Python's own Unicode data, which must be of the version of talcite/src/unicode.cpp (15.1):
# str.casefold gives the full folding, and where that is more than one character the simple one
# is the lowercase letter, except for the three S mappings neither gives.
# Usage: python3 scripts/casing.py tal/src/casing.inc
import sys, unicodedata

WANTED = "15.1.0"
if unicodedata.unidata_version != WANTED:
    sys.exit(f"Python has Unicode {unicodedata.unidata_version}; the tables are of {WANTED}.")

SIMPLE = {0x1FD3: 0x0390, 0x1FE3: 0x03B0, 0xFB05: 0xFB06}

def fold(c):
    if c in SIMPLE: return SIMPLE[c]
    one = chr(c).casefold()
    if len(one) == 1: return ord(one)
    low = chr(c).lower()
    return ord(low) if len(low) == 1 else c

def lower(c):
    low = chr(c).lower()
    return ord(low) if len(low) == 1 else c

def runs(mapping):
    made = []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF or mapping(c) == c: continue
        delta = mapping(c) - c
        if made:
            first, last, step_delta, step = made[-1]
            if step_delta == delta and ((step == 0 and c - last in (1, 2)) or (step and c - last == step)):
                made[-1] = (first, c, delta, step or c - last)
                continue
        made.append((c, c, delta, 0))
    return [(first, last, delta, step or 1) for first, last, delta, step in made]

with open(sys.argv[1], "w", encoding="utf-8") as out:
    out.write(f"// Generated by scripts/casing.py from the Unicode {WANTED} data of Python; not edited by hand.\n")
    for name, mapping in (("folds", fold), ("lowers", lower)):
        table = runs(mapping)
        out.write(f"constexpr std::array<Run, {len(table)}> {name}{{{{\n")
        for first, last, delta, step in table: out.write(f"    {{0x{first:X}, 0x{last:X}, {delta}, {step}}},\n")
        out.write("}};\n")
