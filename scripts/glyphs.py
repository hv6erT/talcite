#!/usr/bin/env python3
# Generates tal/src/glyphs.inc, the tables the text version of PDF reads glyphs by: the names of
# glyphs and their characters (Adobe's glyphlist.txt, from TeX Live, Apache License 2.0, see
# LICENSE-AGL, and a few names of TeX fonts it lacks), the standard encodings of simple fonts by
# code (StandardEncoding from TeX Live's 8a.enc, which is in the public domain; WinAnsiEncoding and
# MacRomanEncoding from Python's codecs cp1252 and mac_roman), the spacing accents with their
# combining marks, the letters an accent and a letter compose to (Python's NFC), and the Cork (T1)
# encoding of TeX's EC fonts by code (from TeX Live's ec.enc), which bitmap fonts of pdfTeX name
# their glyphs by ("/a65").
# Usage: python3 scripts/glyphs.py glyphlist.txt 8a.enc ec.enc tal/src/glyphs.inc
import re, sys, unicodedata

names = {}
for line in open(sys.argv[1], encoding="utf-8"):
    if line.startswith("#") or ";" not in line: continue
    name, codes = line.strip().split(";")
    names[name] = "".join(chr(int(code, 16)) for code in codes.split())
names.update({"dotlessj": "\u0237", "visiblespace": "\u2423", "Ng": "\u014A", "ng": "\u014B", "cwm": "", "suppress": "\u0337"})

encoded = re.findall(r"/([A-Za-z0-9_.]+)", open(sys.argv[2], encoding="latin-1").read().split("[", 1)[1])
assert len(encoded) == 256, len(encoded)
standard = [names.get(one, "") if one != ".notdef" else "" for one in encoded]

cork_names = re.findall(r"/([A-Za-z0-9_.]+)", re.sub(r"%[^\n]*", "", open(sys.argv[3], encoding="latin-1").read()).split("[", 1)[1])
assert len(cork_names) == 256, len(cork_names)
extra = {"Germandbls": "SS", "tcedilla": "\u0163", "Tcedilla": "\u0162", "perthousandzero": "", "compwordmark": "", "dotlessj": "\u0237",
         "visiblespace": "\u2423", "Ng": "\u014A", "ng": "\u014B", "cwm": ""}
cork = [extra[one] if one in extra else names.get(one, "") for one in cork_names]

def codec(name, unused):
    made = []
    for code in range(256):
        try: made.append(bytes([code]).decode(name))
        except UnicodeDecodeError: made.append(unused if code >= 0x80 else "")
    return made

win_ansi = codec("cp1252", "\u2022")
win_ansi[0x7F] = "\u2022"
mac_roman = codec("mac_roman", "")

accents = {"\u00B4": "\u0301", "\u02CA": "\u0301", "`": "\u0300", "\u02CB": "\u0300", "\u02C6": "\u0302", "\u02DC": "\u0303",
           "\u00AF": "\u0304", "\u02C9": "\u0304", "\u02D8": "\u0306", "\u02D9": "\u0307", "\u00A8": "\u0308", "\u02DA": "\u030A",
           "\u02DD": "\u030B", "\u02C7": "\u030C", "\u00B8": "\u0327", "\u02DB": "\u0328", "\u0337": "\u0337"}
composed = []
for base in [chr(c) for c in range(0x41, 0x5B)] + [chr(c) for c in range(0x61, 0x7B)]:
    for mark in sorted(set(accents.values())):
        one = unicodedata.normalize("NFC", base + mark)
        if len(one) == 1: composed.append((ord(base), ord(mark), ord(one)))
# TeX's old fonts draw the letters l and L with stroke as l and L under a short stroke (the glyph
# "suppress"), which Unicode does not compose.
composed += [(ord("L"), 0x0337, 0x0141), (ord("l"), 0x0337, 0x0142)]

def utf8(text): return "".join(f"\\x{byte:02X}" for byte in text.encode("utf-8"))

def points(table):
    return ["0x%04X" % (ord(one) if len(one) == 1 else 0) for one in table]

with open(sys.argv[4], "w", encoding="utf-8") as out:
    out.write("// Generated by scripts/glyphs.py from glyphlist.txt (Adobe, Apache License 2.0, see\n")
    out.write("// LICENSE-AGL), 8a.enc and Python's codecs and NFC; not edited by hand.\n")
    listed = sorted(names)
    out.write(f"constexpr std::array<Glyph, {len(listed)}> glyphs{{{{\n")
    for name in listed: out.write(f'    {{"{name}", "{utf8(names[name])}"}},\n')
    out.write("}};\n")
    for title, table in (("standard_encoding", standard), ("win_ansi_encoding", win_ansi), ("mac_roman_encoding", mac_roman), ("cork_encoding", cork)):
        out.write(f"constexpr std::array<char32_t, 256> {title}{{{{\n")
        cells = points(table)
        for row in range(0, 256, 8): out.write("    " + ", ".join(cells[row:row + 8]) + ",\n")
        out.write("}};\n")
    out.write(f"constexpr std::array<Accent, {len(accents)}> accents{{{{\n")
    for spacing, mark in sorted(accents.items()): out.write(f"    {{0x{ord(spacing):04X}, 0x{ord(mark):04X}}},\n")
    out.write("}};\n")
    out.write(f"constexpr std::array<Composed, {len(composed)}> composed{{{{\n")
    for base, mark, one in sorted(composed): out.write(f"    {{0x{base:04X}, 0x{mark:04X}, 0x{one:04X}}},\n")
    out.write("}};\n")
