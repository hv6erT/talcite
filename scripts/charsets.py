#!/usr/bin/env python3
# Generates tal/src/charsets.inc, the upper halves (0x80 to 0xFF) of the single-byte encodings the
# text versions read: windows-1252, windows-1250 and ISO-8859-2, as the WHATWG Encoding standard
# maps them. Python's codecs give the mapping; the bytes they leave undefined (0x81, 0x8D, 0x8F,
# 0x90 and 0x9D in windows-1252, and 0x81, 0x83, 0x88, 0x90 and 0x98 in windows-1250) map to the
# code point of the same number, as the standard's indexes do.
# Usage: python3 scripts/charsets.py tal/src/charsets.inc
import sys

def half(codec):
    made = []
    for byte in range(0x80, 0x100):
        try:
            made.append(ord(bytes([byte]).decode(codec)))
        except UnicodeDecodeError:
            made.append(byte)
    return made

with open(sys.argv[1], "w", encoding="utf-8") as out:
    out.write("// Generated by scripts/charsets.py from Python's codecs; not edited by hand.\n")
    for name, codec in (("windows_1252", "cp1252"), ("windows_1250", "cp1250"), ("iso_8859_2", "iso8859_2")):
        table = half(codec)
        out.write(f"constexpr std::array<char16_t, 128> {name}{{{{\n")
        for row in range(0, 128, 8):
            out.write("    " + ", ".join(f"0x{one:04X}" for one in table[row:row + 8]) + ",\n")
        out.write("}};\n")
