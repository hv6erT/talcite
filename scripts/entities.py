#!/usr/bin/env python3
# Generates tal/src/entities.inc, the named character references of HTML5 (2231 names, those
# without the semicolon included) for the text version of HTML, from Python's html.entities, which
# carries the table of the WHATWG standard. Sorted by name, so that the reader finds the longest
# name that begins a reference by a binary search.
# Usage: python3 scripts/entities.py tal/src/entities.inc
import sys
from html.entities import html5

def utf8(text):
    return "".join(f"\\x{byte:02X}" for byte in text.encode("utf-8"))

names = sorted(html5)
with open(sys.argv[1], "w", encoding="utf-8") as out:
    out.write("// Generated by scripts/entities.py from Python's html.entities; not edited by hand.\n")
    out.write(f"constexpr std::array<Entity, {len(names)}> entities{{{{\n")
    for name in names:
        out.write(f'    {{"{name}", "{utf8(html5[name])}"}},\n')
    out.write("}};\n")
