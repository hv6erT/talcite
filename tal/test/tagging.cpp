    Counted from{lump("000102030405060708090a0b0c0d0e0f"), 16};
    meta::tagging::Walk walk = tal::wait(loop, meta::tagging::Walk::over(from));

    tal::wait(loop, walk.need(4));

    SAME(from.reads(), std::size_t{1});
    SAME(walk.u8(), std::uint8_t{0});

