// tiny.mkv with the given bytes as the Title of its Info, put together by hand: the Segment's size
// becomes unknown (all ones), the Info gets a size of eight bytes, and the Title one of two bytes,
// so a title of any length up to 16 KiB fits without moving anything else.
[[nodiscard]] Bytes mkv_titled_as(std::string_view said) {
    const Bytes file = lump(mkv_file);
    constexpr std::size_t info = 213;
    constexpr std::size_t inside = 38;

    Bytes made(file.begin(), file.begin() + info + 4);

    for (std::size_t at = 45; at < 52; ++at) made[at] = std::byte{0xFF};

    const std::uint64_t content = inside + 4 + said.size();

    made.push_back(std::byte{0x01});

    for (int shift = 48; shift >= 0; shift -= 8) made.push_back(static_cast<std::byte>((content >> shift) & 0xFF));

    for (const std::uint8_t one : {std::uint8_t{0x7B}, std::uint8_t{0xA9}, static_cast<std::uint8_t>(0x40 | (said.size() >> 8)),
                                   static_cast<std::uint8_t>(said.size() & 0xFF)})
        made.push_back(static_cast<std::byte>(one));

    for (const char one : said) made.push_back(static_cast<std::byte>(one));

    made.insert(made.end(), file.begin() + info + 5, file.end());

    return made;
}

