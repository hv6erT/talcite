// package) and kept here for good: the key of a test server is public by nature, and making keys on
// the fly is fickle under Schannel. A small authority of its own, `authority_pem`, valid for a
// hundred years, signed talcite.test three ways: `identity_hex`, ordinary and valid for a hundred
// years; `expired_hex`, valid in the year 2000; `client_hex`, for clients only. `chained_hex` is
// talcite.test signed by an intermediate authority that `authority_pem` signed, the intermediate
