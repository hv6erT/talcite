// A little-endian number of `width` bytes.
[[nodiscard]] Bytes little(std::uint64_t value, std::size_t width) {
    Bytes made;

    for (std::size_t one = 0; one < width; ++one) made.push_back(static_cast<std::byte>((value >> (8 * one)) & 0xFF));

    return made;
}

// A big-endian number of `width` bytes.
[[nodiscard]] Bytes big(std::uint64_t value, std::size_t width) {
    Bytes made;

    for (std::size_t one = width; one-- > 0;) made.push_back(static_cast<std::byte>((value >> (8 * one)) & 0xFF));

    return made;
}

// An entry of a directory to assemble: the tag, the type, the count, the value's bytes (little-
// endian), or the numbers of the directories it points to.
struct Put {
    std::uint16_t tag = 0;
    std::uint16_t type = 0;
    std::uint32_t count = 0;
    Bytes value;
    std::vector<std::size_t> to;
};

// A directory to assemble and the number of the one after it.
struct Directory {
    std::vector<Put> entries;
    std::optional<std::size_t> next;
};

// A text value (ASCII) with its zero.
[[nodiscard]] Put ascii(std::uint16_t tag, std::string_view text) {
    Bytes value = bytes_of(text);

    value.push_back(std::byte{0});

    return {tag, 2, static_cast<std::uint32_t>(value.size()), value, {}};
}

// A SHORT value.
[[nodiscard]] Put short_of(std::uint16_t tag, std::uint16_t value) { return {tag, 3, 1, little(value, 2), {}}; }

// A LONG value.
[[nodiscard]] Put long_of(std::uint16_t tag, std::uint32_t value) { return {tag, 4, 1, little(value, 4), {}}; }

// A pointer to the directories numbered `to`.
[[nodiscard]] Put pointer(std::uint16_t tag, std::vector<std::size_t> to) { return {tag, 4, static_cast<std::uint32_t>(to.size()), {}, std::move(to)}; }

// A little-endian TIFF structure: the header, the directories one after another, then the values
// longer than four bytes. Pointers and the links between directories become offsets.
[[nodiscard]] Bytes tiffed(const std::vector<Directory>& directories) {
    std::vector<std::size_t> at;
    std::size_t end = 8;

    for (const Directory& one : directories) {
        at.push_back(end);
        end += 2 + 12 * one.entries.size() + 4;
    }

    Bytes made = bytes_of("II*");

    made.push_back(std::byte{0});
    append(made, little(directories.empty() ? 0 : at[0], 4));

    Bytes data;

    for (const Directory& one : directories) {
        append(made, little(one.entries.size(), 2));

        for (const Put& entry : one.entries) {
            append(made, little(entry.tag, 2));
            append(made, little(entry.type, 2));
            append(made, little(entry.count, 4));

            Bytes value = entry.value;

            for (const std::size_t to : entry.to) append(value, little(at[to], 4));

            if (value.size() <= 4) {
                value.resize(4);
                append(made, value);
            } else {
                append(made, little(end + data.size(), 4));
                append(data, value);

                if (data.size() % 2 != 0) data.push_back(std::byte{0});
            }
        }

        append(made, little(one.next ? at[*one.next] : 0, 4));
    }

    append(made, data);

    return made;
}

// A segment of JPEG: the marker, the length and the payload.
[[nodiscard]] Bytes segment(std::uint8_t marker, const Bytes& payload) {
    Bytes made{std::byte{0xFF}, std::byte{marker}};

    append(made, big(payload.size() + 2, 2));
    append(made, payload);

    return made;
}

// A JPEG of the segments, with a frame header of `width` by `height` and the start of a scan after
// them; the scan itself is not needed by the reader.
[[nodiscard]] Bytes jpegged(const std::vector<Bytes>& segments, std::uint16_t width = 4, std::uint16_t height = 2) {
    Bytes made{std::byte{0xFF}, std::byte{0xD8}};

    for (const Bytes& one : segments) append(made, one);

    Bytes frame{std::byte{8}};

    append(frame, big(height, 2));
    append(frame, big(width, 2));
    append(frame, lump("01011100"));
    append(made, segment(0xC0, frame));
    append(made, segment(0xDA, lump("010100003f00")));
    append(made, lump("00ffd9"));

    return made;
}

// A payload that starts with a mark (with its zeros) and goes on with the bytes.
[[nodiscard]] Bytes marked(std::string_view mark, const Bytes& rest) {
    Bytes made = bytes_of(mark);

    append(made, rest);

    return made;
}

