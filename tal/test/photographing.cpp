// The CRC-32 of bytes, as PNG checks its chunks, computed here bit by bit.
[[nodiscard]] std::uint32_t checked(std::span<const std::byte> given) {
    std::uint32_t made = 0xFFFFFFFF;

    for (const std::byte one : given) {
        made ^= std::to_integer<std::uint32_t>(one);

        for (int bit = 0; bit < 8; ++bit) made = (made >> 1) ^ (0xEDB88320u & (0u - (made & 1u)));
    }

    return ~made;
}

// A chunk of PNG: the length, the type, the data and its check.
[[nodiscard]] Bytes chunk(std::string_view type, const Bytes& data) {
    Bytes made = big(data.size(), 4);

    append(made, bytes_of(type));
    append(made, data);
    append(made, big(checked(std::span<const std::byte>{made}.subspan(4)), 4));

    return made;
}

// A PNG of `width` by `height` with the chunks between IHDR and IEND.
[[nodiscard]] Bytes pnged(const std::vector<Bytes>& chunks, std::uint32_t width = 4, std::uint32_t height = 2) {
    Bytes made = lump("89504e470d0a1a0a");
    Bytes header = big(width, 4);

    append(header, big(height, 4));
    append(header, lump("0802000000"));
    append(made, chunk("IHDR", header));

    for (const Bytes& one : chunks) append(made, one);

    append(made, chunk("IEND", {}));

    return made;
}

// The bytes in the zlib format, of stored DEFLATE blocks with a true Adler-32.
[[nodiscard]] Bytes zlibbed(const Bytes& given) {
    Bytes made = lump("7801");
    std::size_t at = 0;

    do {
        const std::size_t much = std::min<std::size_t>(65535, given.size() - at);

        made.push_back(std::byte{static_cast<std::uint8_t>(at + much == given.size() ? 1 : 0)});
        append(made, little(much, 2));
        append(made, little(~much & 0xFFFF, 2));
        made.insert(made.end(), given.begin() + static_cast<std::ptrdiff_t>(at), given.begin() + static_cast<std::ptrdiff_t>(at + much));
        at += much;
    } while (at < given.size());

    std::uint32_t low = 1;
    std::uint32_t high = 0;

    for (const std::byte one : given) {
        low = (low + std::to_integer<std::uint32_t>(one)) % 65521;
        high = (high + low) % 65521;
    }

    append(made, big((std::uint64_t{high} << 16) | low, 4));

    return made;
}

// A box of ISO-BMFF: its size, its type and its body.
[[nodiscard]] Bytes box(std::string_view type, const Bytes& body) {
    Bytes made = big(8 + body.size(), 4);

    append(made, bytes_of(type));
    append(made, body);

    return made;
}

// A full box: a box whose body starts with a version and three bytes of flags.
[[nodiscard]] Bytes full(std::string_view type, std::uint8_t version, std::uint32_t flags, const Bytes& body) {
    Bytes inner = big((std::uint64_t{version} << 24) | flags, 4);

    append(inner, body);

    return box(type, inner);
}

